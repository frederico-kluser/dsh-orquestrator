import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { isAbsolute, join } from 'node:path'
import { after, describe, it } from 'node:test'
import { fileURLToPath, pathToFileURL } from 'node:url'
import type { SkillRegistrationLike, SkillsLike } from '../../src/host-services.ts'
import { SKILL_NAME } from '../../src/shared.ts'
import { SKILL_SOURCE } from '../../src/skill.generated.ts'
import { bundledSkillPath, registerOrchestrationSkill, skillRegistration } from '../../src/skill.ts'

const root = fileURLToPath(new URL('../../', import.meta.url))
const script = join(root, 'scripts', 'gen-skill.mjs')
const skillFile = join(root, 'skills', 'orchestrate-subagents', 'SKILL.md')
// The real path: a module imported from here reports it (a temp directory is often a symlink, as `/var` is on macOS).
const scratch = realpathSync(mkdtempSync(join(tmpdir(), 'orq-skill-')))
// The scratch directory holds generated `.ts` modules the tests import: give it its own ES module scope.
writeFileSync(join(scratch, 'package.json'), '{ "type": "module" }')
after(() => { rmSync(scratch, { recursive: true, force: true }) })

/** The generated module, widened so the tests type-check whether or not the Markdown carries `when-to-use`. */
const real: { readonly name: string; readonly description: string; readonly whenToUse?: string; readonly content: string } = SKILL_SOURCE

/** Run the generator the way a developer does: through its command line. */
function generate(args: readonly string[], cwd = root): { readonly status: number | null; readonly stdout: string; readonly stderr: string } {
  const { status, stdout, stderr } = spawnSync(process.execPath, [script, ...args], { cwd, encoding: 'utf8' })
  return { status, stdout, stderr }
}

let fixtures = 0
/** Write a SKILL.md fixture; every call gets a fresh pair of file names, so an imported module is never a stale cached one. */
function fixture(markdown: string): { readonly source: string; readonly out: string } {
  fixtures += 1
  const source = join(scratch, `skill-${String(fixtures)}.md`)
  writeFileSync(source, markdown)
  return { source, out: join(scratch, `skill-${String(fixtures)}.generated.ts`) }
}

/** Generate a module from Markdown and import what it exports. */
async function generated(markdown: string): Promise<Readonly<Record<string, unknown>>> {
  const { source, out } = fixture(markdown)
  const result = generate(['--source', source, '--out', out])
  assert.equal(result.status, 0, result.stderr)
  return ((await import(pathToFileURL(out).href)) as { SKILL_SOURCE: Readonly<Record<string, unknown>> }).SKILL_SOURCE
}

/** A SKILL.md: frontmatter lines, then the body lines. */
function markdown(frontmatter: readonly string[], ...body: readonly string[]): string {
  return ['---', ...frontmatter, '---', ...body].join('\n')
}

