/** A registry double that records what it is given and counts the disposals. */
interface FakeRegistry {
  readonly skills: SkillsLike
  readonly registered: SkillRegistrationLike[]
  disposals: number
}

/**
 * A registry double. With no failure it applies the rules of DSH 0.1.6-alpha.2's `validateRuntimeSkill` (a copy of
 * packages/skill/skill/src/index.ts), so that a registration DSH would refuse fails here too; with a failure it throws it.
 */
function fakeRegistry(failure?: unknown): FakeRegistry {
  const fake: FakeRegistry = {
    registered: [],
    disposals: 0,
    skills: {
      register(skill) {
        if (failure !== undefined) throw failure
        if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(skill.name)) throw new Error(`invalid skill name "${skill.name}"`)
        if (skill.description.length === 0) throw new Error(`skill "${skill.name}" requires a description`)
        if (typeof skill.invocation?.modelInvocable !== 'boolean' || typeof skill.invocation.userInvocable !== 'boolean') throw new TypeError('invocation policy')
        if (typeof skill.content !== 'string' || typeof skill.source !== 'string') throw new TypeError('content and source must be strings')
        if (skill.path !== undefined && typeof skill.path !== 'string') throw new TypeError('path must be a string')
        fake.registered.push(skill)
        return () => { fake.disposals += 1 }
      },
    },
  }
  return fake
}

/** A logger double. */
function fakeLogger(): { readonly logger: { info(message: string): void; warn(message: string): void }; readonly info: string[]; readonly warn: string[] } {
  const info: string[] = []
  const warn: string[] = []
  return { logger: { info: message => { info.push(message) }, warn: message => { warn.push(message) } }, info, warn }
}

describe('registerOrchestrationSkill', () => {
  it('registers the skill once, with its text, its path and the operator\'s invocation choice, and says so', () => {
    const registry = fakeRegistry()
    const log = fakeLogger()
    const handle = registerOrchestrationSkill(registry.skills, { modelInvocable: true }, log.logger)
    assert.equal(handle.available, true)
    assert.equal(registry.registered.length, 1)
    assert.deepEqual(registry.registered[0], skillRegistration({ modelInvocable: true }, skillFile))
    assert.equal(registry.registered[0]?.name, SKILL_NAME)
    assert.equal('resourceBase' in (registry.registered[0] ?? {}), false)
    assert.deepEqual(log.info, ['dsh-orquestrator: registered the global skill "orchestrate-subagents" (model-invocable: yes)'])
    assert.deepEqual(log.warn, [])
    assert.equal(registry.disposals, 0)
  })

  it('keeps the skill out of the model\'s catalog when the operator says so, and the log says no', () => {
    const registry = fakeRegistry()
    const log = fakeLogger()
    registerOrchestrationSkill(registry.skills, { modelInvocable: false }, log.logger)
    assert.deepEqual(registry.registered[0]?.invocation, { modelInvocable: false, userInvocable: true })
    assert.deepEqual(log.info, ['dsh-orquestrator: registered the global skill "orchestrate-subagents" (model-invocable: no)'])
  })

  it('unregisters through the registry\'s disposer, once, however often dispose is called', () => {
    const registry = fakeRegistry()
    const handle = registerOrchestrationSkill(registry.skills, { modelInvocable: true }, fakeLogger().logger)
    handle.dispose()
    handle.dispose()
    assert.equal(registry.disposals, 1)
  })

  it('answers unavailable, with a warning and no error, when the registry refuses the skill', () => {
    const registry = fakeRegistry(new Error('a skill named "orchestrate-subagents" is reserved'))
    const log = fakeLogger()
    const handle = registerOrchestrationSkill(registry.skills, { modelInvocable: true }, log.logger)
    assert.equal(handle.available, false)
    assert.deepEqual(log.warn, ['dsh-orquestrator: could not register the global skill "orchestrate-subagents": a skill named "orchestrate-subagents" is reserved; the dialog will not offer it'])
    assert.deepEqual(log.info, [])
    assert.equal(registry.registered.length, 0)
    assert.doesNotThrow(() => { handle.dispose(); handle.dispose() })
    assert.equal(registry.disposals, 0)
  })

  it('reports whatever was thrown, an Error or not', () => {
    const log = fakeLogger()
    assert.equal(registerOrchestrationSkill(fakeRegistry('plain text').skills, { modelInvocable: true }, log.logger).available, false)
    assert.match(log.warn[0] ?? '', /: plain text; the dialog will not offer it$/)
  })

  it('does not throw when there is no registry to register with', () => {
    const log = fakeLogger()
    const handle = registerOrchestrationSkill(undefined as unknown as SkillsLike, { modelInvocable: true }, log.logger)
    assert.equal(handle.available, false)
    assert.equal(log.warn.length, 1)
  })

  it('registers what a registry that checks like DSH\'s accepts, with a description inside the catalog\'s limit', () => {
    const registry = fakeRegistry()
    assert.equal(registerOrchestrationSkill(registry.skills, { modelInvocable: true }, fakeLogger().logger).available, true)
    assert.ok((registry.registered[0]?.description.length ?? 0) <= 500)
  })
})
